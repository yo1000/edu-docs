// 変数と文字列
// DevTools の Console に、1行ずつ（関数や複数行の文はまとめて）貼り付けて実行する。
// 別のファイルを試すときは、ページを再読み込み（F5）してから貼り付ける（同じ名前の const が重複するとエラーになるため）

const title = "設計書を読む"; // 再代入できない（Javaの final に近い）
let count = 0; // 再代入できる
count = count + 1;
count = "いっぱい"; // エラーにならない。変数に型がないため

const a = "ダブルクォート"; // " で囲む
const b = 'シングルクォート'; // ' で囲む。" と同じ意味で、どちらもよく使われる
const name = "佐藤";
const c = `${name}さん、こんにちは`; // ` で囲むと ${ } で値を埋め込める（テンプレートリテラル）

const d = /^task/; // / で囲むと正規表現（RegExp オブジェクト）
